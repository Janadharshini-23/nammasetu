def main():
    with open(DATA_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)

    updated = 0
    for scheme in data:
        slug = scheme["slug"]
        if slug in TRANSLATIONS:
            scheme["ta"] = TRANSLATIONS[slug]["ta"]
            scheme["te"] = TRANSLATIONS[slug]["te"]
            updated += 1

    with open(DATA_PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"Successfully updated {updated} schemes in {DATA_PATH} with ta and te translations!")

if __name__ == "__main__":
    main()
